"""Extract real test cases from Pinecone corpus.

Run this once to generate real_test_cases.py, then use those for evals.

This queries Pinecone for actual issues ingested by ingest.py and extracts
metadata so you can test against real data from the corpus.
"""

from __future__ import annotations

import os
import json
from collections import defaultdict
from dotenv import load_dotenv
from pinecone import Pinecone

load_dotenv()

INDEX_NAME = "resolveflow-issues"

def extract_test_cases(num_per_repo: int = 2) -> dict:
    """
    Query Pinecone and extract real test cases.

    Returns dict mapping repo -> list of (issue_number, title, first_chunk_text)
    """
    pc = Pinecone(api_key=os.environ["PINECONE_API_KEY"])
    index = pc.Index(host=pc.describe_index(INDEX_NAME).host)

    # Get stats to see what's in the index
    stats = index.describe_index_stats()
    print(f"Index has {stats['total_vector_count']} vectors")

    # Query for documents (using a generic query to get diverse results)
    # We'll use namespace stats if available, otherwise query top-level
    vector_store_stats = stats.get("namespaces", {}).get("", {})
    print(f"Documents in default namespace: {vector_store_stats}")

    # Extract unique issues from the index metadata
    # We'll fetch a sample of vectors and extract issue info from their IDs
    issues_by_repo = defaultdict(list)

    # Query with a generic vector (all ones) to get arbitrary documents
    # This is a bit of a hack, but Pinecone doesn't have a "list all" API
    generic_query = [0.01] * 512  # 512-dim vector (matching our embedding dim)

    try:
        results = index.query(vector=generic_query, top_k=100, include_metadata=True)

        seen_issues = set()
        for match in results.get("matches", []):
            # Extract info from metadata
            metadata = match.get("metadata", {})
            source = metadata.get("source", "")

            # Source format: "facebook-react-issue-12345#0"
            # Parse it to get repo and issue number
            if "issue-" in source:
                parts = source.split("-issue-")
                repo_part = parts[0].replace("-", "/")  # "facebook-react" -> "facebook/react"

                # Handle both "facebook-react" and compound names
                if repo_part.startswith("facebook") or repo_part.startswith("langchain") or \
                   repo_part.startswith("microsoft") or repo_part.startswith("vercel"):
                    # Extract issue number (before the #chunk_id)
                    issue_part = parts[1].split("#")[0]

                    try:
                        issue_num = int(issue_part)
                    except ValueError:
                        continue

                    issue_key = (repo_part, issue_num)
                    if issue_key not in seen_issues:
                        seen_issues.add(issue_key)

                        # Map back to actual repo name
                        repo_name = _map_repo_name(repo_part)

                        page_content = match.get("metadata", {}).get("page_content", "")
                        issues_by_repo[repo_name].append({
                            "issue_number": issue_num,
                            "content": page_content[:300],  # First 300 chars
                            "source": source
                        })

                        if len(seen_issues) >= num_per_repo * 4:  # Get enough samples
                            break

    except Exception as e:
        print(f"Error querying Pinecone: {e}")
        return {}

    # Limit to num_per_repo per repo
    result = {}
    for repo, issues in issues_by_repo.items():
        result[repo] = issues[:num_per_repo]

    return result

def _map_repo_name(shortened: str) -> str:
    """Map shortened repo names back to full names."""
    mapping = {
        "facebook": "facebook/react",
        "langchain": "langchain-ai/langchain",
        "microsoft": "microsoft/terminal",
        "vercel": "vercel/next.js",
    }
    for key, full in mapping.items():
        if shortened.startswith(key):
            return full
    return shortened

def generate_test_cases_file(test_cases: dict) -> str:
    """Generate Python code for real_test_cases.py"""

    code = '''"""Real test cases extracted from Pinecone corpus.

These are actual closed issues that are in the ingested corpus.
They provide realistic test data for capability evals.

Generated by: python -m eval.extract_real_test_cases
"""

from __future__ import annotations

from schemas.evidence import IssueEvidence

REAL_TEST_CASES = [
'''

    case_num = 0
    for repo, issues in test_cases.items():
        for issue in issues:
            issue_num = issue["issue_number"]
            content = issue["content"].replace('"', '\\"').replace('\n', ' ')

            code += f'''    IssueEvidence(
        repo="{repo}",
        issue_number={issue_num},
        title="Real issue from {repo}",
        body="{content}...",
        comments=[]
    ),
'''
            case_num += 1

    code += ''']
'''
    return code

def main() -> None:
    print("Extracting real test cases from Pinecone...")
    test_cases = extract_test_cases(num_per_repo=2)

    if not test_cases:
        print("⚠️  Could not extract test cases. Is Pinecone populated?")
        print("Run: python ingest.py")
        return

    print(f"Found {sum(len(v) for v in test_cases.values())} test cases across repos:")
    for repo, issues in test_cases.items():
        print(f"  {repo}: {len(issues)} issues")

    # Generate the file
    code = generate_test_cases_file(test_cases)

    output_file = "eval/real_test_cases.py"
    with open(output_file, "w") as f:
        f.write(code)

    print(f"\n✓ Generated {output_file}")
    print("\nNow update capability_harness.py to use:")
    print("  from eval.real_test_cases import REAL_TEST_CASES")

if __name__ == "__main__":
    main()
