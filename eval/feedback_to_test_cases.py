"""Convert customer feedback into test cases for evals.

When customers report that a diagnosis was "incorrect" or "incomplete",
add those issues to the eval suite so we can catch regressions.

Usage: python -m eval.feedback_to_test_cases

This reads the feedback table from Postgres and generates/updates
eval/customer_feedback_issues.py with test cases.
"""

from __future__ import annotations

import os
from dotenv import load_dotenv
from psycopg_pool import AsyncConnectionPool
import asyncio

load_dotenv()

DATABASE_URL = os.environ["DATABASE_URL"]


async def fetch_negative_feedback() -> list[dict]:
    """Fetch all 'incorrect' and 'incomplete' feedback from the database."""
    pool = AsyncConnectionPool(DATABASE_URL, open=False)
    await pool.open()

    async with pool.connection() as conn:
        cur = await conn.execute(
            """
            SELECT DISTINCT repo, issue_number, verdict, reason, COUNT(*) as count
            FROM feedback
            WHERE verdict IN ('incorrect', 'incomplete')
            GROUP BY repo, issue_number, verdict, reason
            ORDER BY count DESC
            """
        )
        rows = await cur.fetchall()

    await pool.close()

    return [
        {
            "repo": row[0],
            "issue_number": row[1],
            "verdict": row[2],
            "reason": row[3],
            "feedback_count": row[4],
        }
        for row in rows
    ]


